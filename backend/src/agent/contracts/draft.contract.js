'use strict';

/**
 * Draft Output Contract
 *
 * CRITICAL: This file defines what a "draft" is in Organia.
 *
 * All drafts MUST use this structure. No free-form text outside sections.
 * This enables:
 * - UI rendering
 * - Approval workflows
 * - Diffing and version control
 * - Translation
 *
 * If a draft type is missing, it MUST be added here explicitly.
 */

/**
 * Draft Types (ENUM)
 *
 * These are the ONLY permitted draft types.
 * Any tool emitting a different type MUST throw an error.
 */
const DRAFT_TYPE = Object.freeze({
  /**
   * INVITATION
   * Formal invitation to a session (hearing, meeting, consultation, etc.)
   */
  INVITATION: 'INVITATION',

  /**
   * CLIENT_EMAIL
   * Email communication to a client regarding lawsuit/dossier
   */
  CLIENT_EMAIL: 'CLIENT_EMAIL',

  /**
   * HEARING_SUMMARY
   * Summary of a completed hearing or session
   */
  HEARING_SUMMARY: 'HEARING_SUMMARY',

  /**
   * INTERNAL_NOTE
   * Internal note or memo for file documentation
   */
  INTERNAL_NOTE: 'INTERNAL_NOTE',
});

/**
 * Draft Tone (ENUM)
 *
 * Tone for generated drafts.
 * Affects language formality and style.
 */
const DRAFT_TONE = Object.freeze({
  /**
   * FORMAL
   * Highly formal language, suitable for court documents and official correspondence
   */
  FORMAL: 'FORMAL',

  /**
   * NEUTRAL
   * Professional but approachable tone, suitable for most client communication
   */
  NEUTRAL: 'NEUTRAL',
});

/**
 * Draft Source (ENUM)
 *
 * Indicates how the draft was generated.
 */
const DRAFT_SOURCE = Object.freeze({
  /**
   * RULE_BASED
   * Generated by deterministic rule-based reasoner
   */
  RULE_BASED: 'rule-based',

  /**
   * LLM
   * Generated by LLM reasoner (v3 only)
   */
  LLM: 'llm',
});

/**
 * Validate that a draft type is valid
 * @param {string} type - Draft type to validate
 * @throws {Error} If type is not in enum
 */
function validateDraftType(type) {
  const validTypes = Object.values(DRAFT_TYPE);
  if (!validTypes.includes(type)) {
    throw new Error(
      `Invalid draft type: "${type}". Must be one of: ${validTypes.join(', ')}`
    );
  }
}

/**
 * Validate that a draft tone is valid
 * @param {string} tone - Draft tone to validate
 * @throws {Error} If tone is not in enum
 */
function validateDraftTone(tone) {
  const validTones = Object.values(DRAFT_TONE);
  if (!validTones.includes(tone)) {
    throw new Error(
      `Invalid draft tone: "${type}". Must be one of: ${validTones.join(', ')}`
    );
  }
}

/**
 * Validate that a draft source is valid
 * @param {string} source - Draft source to validate
 * @throws {Error} If source is not in enum
 */
function validateDraftSource(source) {
  const validSources = Object.values(DRAFT_SOURCE);
  if (!validSources.includes(source)) {
    throw new Error(
      `Invalid draft source: "${source}". Must be one of: ${validSources.join(', ')}`
    );
  }
}

/**
 * Create a draft object with validation
 * @param {Object} draft - Draft data
 * @param {string} draft.type - Draft type (must be from DRAFT_TYPE enum)
 * @param {string} draft.language - ISO language code (e.g., 'en', 'fr')
 * @param {string} draft.tone - Draft tone (must be from DRAFT_TONE enum)
 * @param {Object} draft.sections - Draft sections
 * @param {string} draft.sections.header - Header section (recipient, subject, date, etc.)
 * @param {string} draft.sections.body - Main body content
 * @param {string} draft.sections.footer - Footer section (signature, closing, etc.)
 * @param {Object} draft.metadata - Draft metadata
 * @param {string} draft.metadata.source - Draft source (rule-based or llm)
 * @param {Object} [draft.recipient] - Optional recipient information
 * @param {Object} [draft.context] - Optional context information (entityRef, etc.)
 * @returns {Object} Validated draft object
 * @throws {Error} If validation fails
 */
function createDraft({
  type,
  language,
  tone,
  sections,
  metadata,
  recipient = null,
  context = null,
}) {
  // Validate type
  validateDraftType(type);

  // Validate tone
  validateDraftTone(tone);

  // Validate source
  validateDraftSource(metadata.source);

  // Validate language (basic check for ISO code format)
  if (!language || typeof language !== 'string' || language.length !== 2) {
    throw new Error('Draft language must be a 2-letter ISO code (e.g., "en", "fr")');
  }

  // Validate sections
  if (!sections || typeof sections !== 'object') {
    throw new Error('Draft sections are required and must be an object');
  }

  const requiredSections = ['header', 'body', 'footer'];
  requiredSections.forEach(section => {
    if (!(section in sections)) {
      throw new Error(`Draft section "${section}" is required`);
    }
    if (typeof sections[section] !== 'string') {
      throw new Error(`Draft section "${section}" must be a string`);
    }
  });

  // Validate metadata
  if (!metadata || typeof metadata !== 'object') {
    throw new Error('Draft metadata is required');
  }

  const requiredMetadataFields = ['source', 'status', 'requiresValidation', 'createdAt'];
  requiredMetadataFields.forEach(field => {
    if (!(field in metadata)) {
      throw new Error(`Draft metadata field "${field}" is required`);
    }
  });

  // Enforce status = draft
  if (metadata.status !== 'draft') {
    throw new Error('Draft metadata status must be "draft"');
  }

  // Enforce requiresValidation = true
  if (metadata.requiresValidation !== true) {
    throw new Error('Draft metadata requiresValidation must be true');
  }

  // No free-form text fields allowed outside sections
  const forbiddenFields = ['text', 'content', 'message'];
  forbiddenFields.forEach(field => {
    if (field in arguments[0]) {
      throw new Error(
        `Draft object must not contain "${field}". All content must be in sections (header/body/footer).`
      );
    }
  });

  return Object.freeze({
    type,
    language,
    tone,
    sections: Object.freeze({
      header: sections.header,
      body: sections.body,
      footer: sections.footer,
    }),
    metadata: Object.freeze({
      source: metadata.source,
      status: 'draft',
      requiresValidation: true,
      createdAt: metadata.createdAt || new Date().toISOString(),
    }),
    recipient: recipient ? Object.freeze(recipient) : null,
    context: context ? Object.freeze(context) : null,
  });
}

/**
 * Get draft type metadata
 * @param {string} type - Draft type
 * @returns {Object} Type metadata
 */
function getDraftTypeMetadata(type) {
  validateDraftType(type);

  const metadata = {
    [DRAFT_TYPE.INVITATION]: {
      name: 'Session Invitation',
      requiresRecipient: true,
      requiresContext: true,
    },
    [DRAFT_TYPE.CLIENT_EMAIL]: {
      name: 'Client Email',
      requiresRecipient: true,
      requiresContext: true,
    },
    [DRAFT_TYPE.HEARING_SUMMARY]: {
      name: 'Hearing Summary',
      requiresRecipient: false,
      requiresContext: true,
    },
    [DRAFT_TYPE.INTERNAL_NOTE]: {
      name: 'Internal Note',
      requiresRecipient: false,
      requiresContext: true,
    },
  };

  return metadata[type];
}

module.exports = {
  DRAFT_TYPE,
  DRAFT_TONE,
  DRAFT_SOURCE,
  validateDraftType,
  validateDraftTone,
  validateDraftSource,
  createDraft,
  getDraftTypeMetadata,
};
